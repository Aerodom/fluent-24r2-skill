#!/usr/bin/env python
# -*- coding: utf-8 -*-
"""
生成"一次性串行渲染多帧压力云图"的 Fluent journal。

背景（三条实测结论）：
  1. 多帧渲染必须在【一次 Fluent 会话内串行完成】。每帧重启 Fluent 极慢
     （8 帧串行约 2 分钟；逐帧重启要半小时以上）。
  2. 每帧 save-picture 前【必须加 /display/re-render】。否则第二帧起抓到的是
     上一帧画面，典型表现是"只有网格没有云图"。
  3. 切面（plane）在【每帧 read-data 之后重建】，且切面名【逐帧唯一】。
     这是实际跑通并产出正确云图的 journal 的结构；只建一次的做法不可靠。

用法示例：
    python make_render_journal.py \
        --case <CASE_DIR>/final.cas.h5 \
        --dat-dir <CASE_DIR> --dat-template "b2_trans-1-%05d.dat.h5" \
        --steps 20,40,60,80,100,120,160,200 \
        --var pressure --min 0 --max 600000 \
        --outdir <OUT_DIR> --out <OUT_DIR>/render.jou

生成结构：
    read-case -> 设云图选项/图片分辨率
      -> (逐帧: read-data -> 建切面 pl_<step> -> 指定该切面 -> contour var min max
                -> re-render -> save-picture)
      -> exit
"""
import argparse
import os


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--case", required=True, help="case 文件（.cas.h5）")
    ap.add_argument("--frames", nargs="*", default=None, help="显式的 data 文件列表")
    ap.add_argument("--dat-dir", default=None, help="data 所在目录（配合 --dat-template/--steps）")
    ap.add_argument("--dat-template", default=None, help="如 b2_trans-1-%05d.dat.h5")
    ap.add_argument("--steps", default=None, help="逗号分隔的时间步号，如 20,40,60")

    ap.add_argument("--plane-prefix", default="pl", help="切面名前缀，默认 pl")
    ap.add_argument("--plane-point", default="0 0 0", help="切面上一点，默认 0 0 0")
    ap.add_argument("--plane-normal", default="0 1 0", help="切面法向，默认 0 1 0（水平面）")

    ap.add_argument("--var", default="pressure", help="云图变量名，默认 pressure")
    ap.add_argument("--min", default="0", help="色标下限（与 Fluent 内部单位一致）")
    ap.add_argument("--max", default="600000", help="色标上限")
    ap.add_argument("--res", nargs=2, default=["1600", "900"], help="图片分辨率，默认 1600 900")

    ap.add_argument("--outdir", required=True, help="PNG 输出目录")
    ap.add_argument("--prefix", default="pic", help="PNG 前缀，默认 pic")
    ap.add_argument("--out", required=True, help="生成的 journal 路径")
    ap.add_argument("--no-exit", action="store_true", help="不追加 /exit（用于交互调试）")
    args = ap.parse_args()

    frames = []
    if args.frames:
        frames = list(args.frames)
    elif args.dat_dir and args.dat_template and args.steps:
        for s in [x.strip() for x in args.steps.split(",") if x.strip()]:
            frames.append(os.path.join(args.dat_dir, args.dat_template % int(s)))
    else:
        raise SystemExit("请用 --frames 给出 data 列表，或用 --dat-dir + --dat-template + --steps")

    def fnum(v):
        f = float(v)
        return str(int(f)) if f == int(f) else str(f)

    point = " ".join(fnum(x) for x in args.plane_point.split())
    normal = " ".join(fnum(x) for x in args.plane_normal.split())

    def tag_of(fp, idx):
        stem = os.path.basename(fp).replace(".dat.h5", "").replace(".dat", "")
        for part in reversed(stem.split("-")):
            if part.isdigit():
                return part.zfill(5)
        return "%03d" % idx

    L = ["; auto-generated by make_render_journal.py\n"]
    L.append('/file/read-case "%s"\n' % args.case.replace("\\", "/"))
    L.append("/display/set/picture/x-resolution %s\n" % args.res[0])
    L.append("/display/set/picture/y-resolution %s\n" % args.res[1])

    for i, fp in enumerate(frames, 1):
        tag = tag_of(fp, i)
        plane = "%s_%s" % (args.plane_prefix, tag)
        dst = os.path.join(args.outdir, "%s_%s.png" % (args.prefix, tag)).replace("\\", "/")

        L.append('\n/file/read-data "%s"\n' % fp.replace("\\", "/"))
        L.append("/display/surface/plane-point-n-normal %s %s %s\n" % (plane, point, normal))
        L.append("/display/set/contours/surfaces (%s)\n" % plane)
        L.append("/display/contour\n%s\n%s\n%s\n" % (args.var, fnum(args.min), fnum(args.max)))
        L.append("/display/re-render\n")
        L.append('/display/save-picture "%s"\n' % dst)

    if not args.no_exit:
        L.append("\n/exit\nyes\n")

    os.makedirs(os.path.dirname(os.path.abspath(args.out)) or ".", exist_ok=True)
    os.makedirs(args.outdir, exist_ok=True)
    with open(args.out, "w", encoding="utf-8", newline="\n") as fh:
        fh.write("".join(L))

    print("journal -> %s" % args.out)
    print("帧数 = %d" % len(frames))
    for i, fp in enumerate(frames, 1):
        print("  %2d  %s" % (i, fp.replace("\\", "/")))


if __name__ == "__main__":
    main()

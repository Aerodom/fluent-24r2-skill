#!/usr/bin/env python
# -*- coding: utf-8 -*-
"""
批量导出多帧场数据的 Fluent journal 生成器（/file/export/ascii）
================================================================
用途：把一组 data 帧的单元场（浓度 / 压力 / 相体积分数）导成 .xyz 文本，
      供 rasterize_field_to_grid.py 栅格化为下游危险区掩膜。

为什么单独做脚本：/file/export/ascii 是**交互式**命令，每个帧要逐行给 5 个答案，
手写 13 帧 = 65 行，极易漏行；漏一行就会吃掉后续命令让整个 journal 停摆。

实测确认的交互序列（本脚本按此生成）：
    /file/export/ascii "<out>.xyz"
    ()                      <- Surfaces(1) [()]        空 = 全部
    no                      <- Delimiter/Comma?         no = 空格分隔
    <变量名>                <- ASCII scalar(1)
    ()                      <- ASCII scalar(2)          空 = 结束变量列表
    yes                     <- Location/Cell-Centered?  yes = 单元中心值

关键：Location/Cell-Centered? 必须答 yes。选 no 会输出节点插值值，
节点数 != 单元数，栅格化时对不上。

用法：
    python export_field_journal.py \\
        --case "<CASE_DIR>/G3_files/dp0/FLTG/Fluent/FLTG-1.cas.h5" \\
        --data-dir "<CASE_DIR>/G3_files/dp0/FLTG/Fluent" \\
        --dat-template "FLTG-1-%05d.dat.h5" \\
        --steps 0,200,400,600,800,1000,1200,1400,1600,1800,2000,2200,2262 \\
        --var molef-so2 \\
        --outdir "<CASE_DIR>/export" \\
        --prefix so2 \\
        --out "<CASE_DIR>/work/extract_all.jou"

生成的文件名规则：<outdir>/<prefix>_<step 补零5位>.xyz
"""
import argparse
import os


def p(x):
    """统一正斜杠：Fluent journal 在 Windows 下对混合斜杠敏感。"""
    return str(x).replace("\\", "/")


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--case", required=True, help="case 文件（.cas.h5）")
    ap.add_argument("--frames", nargs="*", default=None,
                    help="显式的 data 文件列表（与 --data-dir/--steps 二选一）")
    ap.add_argument("--data-dir", default=None, help="data 所在目录")
    ap.add_argument("--dat-template", default=None, help="如 FLTG-1-%05d.dat.h5")
    ap.add_argument("--steps", default=None, help="逗号分隔的步号，如 0,200,400")

    ap.add_argument("--var", action="append", required=True,
                    help="要导出的变量名，可重复（如 --var molef-so2 --var pressure）")
    ap.add_argument("--center", action="store_true", default=True,
                    help="导出单元中心值（默认，推荐）。加 --no-center 则导节点值")
    ap.add_argument("--no-center", dest="center", action="store_false")

    ap.add_argument("--outdir", required=True, help=".xyz 输出目录")
    ap.add_argument("--prefix", default="field", help=".xyz 文件名前缀，默认 field")
    ap.add_argument("--tag-width", type=int, default=5, help="步号补零位数，默认 5")
    ap.add_argument("--out", required=True, help="生成的 journal 路径")
    ap.add_argument("--no-exit", action="store_true", help="不追加 /exit")
    args = ap.parse_args()

    frames = []
    if args.frames:
        frames = list(args.frames)
    elif args.data_dir and args.dat_template and args.steps:
        for s in [x.strip() for x in args.steps.split(",") if x.strip()]:
            frames.append(os.path.join(args.data_dir, args.dat_template % int(s)))
    else:
        raise SystemExit("请用 --frames 给出 data 列表，或用 "
                         "--data-dir + --dat-template + --steps")

    def tag_of(fp, idx):
        """从文件名里取最后一段数字作为步号标签。"""
        stem = os.path.basename(p(fp)).replace(".dat.h5", "").replace(".dat", "")
        for part in reversed(stem.split("-")):
            if part.isdigit():
                return part.zfill(args.tag_width)
        return "%0*d" % (args.tag_width, idx)

    L = ["; auto-generated by export_field_journal.py\n"]
    L.append('; 变量: %s   单元中心: %s\n' % (", ".join(args.var), args.center))
    L.append('/file/read-case "%s"\n' % p(args.case))

    for i, fp in enumerate(frames, 1):
        tag = tag_of(fp, i)
        dst = os.path.join(args.outdir, "%s_%s.xyz" % (args.prefix, tag))
        L.append('\n/file/read-data "%s"\n' % p(fp))
        L.append('/file/export/ascii "%s"\n' % p(dst))
        L.append("()\n")          # Surfaces: 空 = 全部
        L.append("no\n")          # Delimiter/Comma? -> 空格分隔
        for v in args.var:
            L.append("%s\n" % v)  # ASCII scalar(1..n)
        L.append("()\n")          # 结束变量列表
        L.append("%s\n" % ("yes" if args.center else "no"))   # Cell-Centered?

    if not args.no_exit:
        L.append("\n/exit\n")

    os.makedirs(os.path.dirname(os.path.abspath(args.out)) or ".", exist_ok=True)
    os.makedirs(args.outdir, exist_ok=True)
    with open(args.out, "w", encoding="utf-8", newline="\n") as fh:
        fh.write("".join(L))

    print("journal -> %s" % p(args.out))
    print("case    : %s" % p(args.case))
    print("变量    : %s   单元中心 = %s" % (", ".join(args.var), args.center))
    print("帧数    = %d" % len(frames))
    for i, fp in enumerate(frames, 1):
        tag = tag_of(fp, i)
        print("  %2d  step=%-6s  %s" % (i, tag, p(fp)))
    print()
    print("运行：python run_fluent_journal.py --journal \"%s\"" % p(args.out))
    print()
    print("自检：导出完成后核对 .xyz 表头应为")
    print("  cellnumber x-coordinate y-coordinate z-coordinate %s" % " ".join(args.var))
    print("  且数据行数 == 网格单元数（用 wc -l 减 1）。")


if __name__ == "__main__":
    main()
